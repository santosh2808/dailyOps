import { createHmac, timingSafeEqual } from 'crypto';

// Short-lived signed link for viewing a JEO PDF in the browser's own PDF
// viewer. The app used to fetch the PDF with the login token and open it
// as a blob: URL, which can't carry a file name — so the viewer's download
// button saved it under the blob's random id. A real URL ending in the
// file name (…/JEO%204004.pdf) with a matching Content-Disposition is what
// browsers name the download after. The URL can't send the login token, so it holds
// this instead: issued only to a logged-in user with JEO View, valid for
// one JEO and a few minutes, and signed with a key derived from JWT_SECRET
// for this purpose only (so it can never pass as a login token, nor a
// login token as one of these).
export const JEO_PDF_LINK_TTL_MS = 15 * 60 * 1000;

interface JeoPdfLinkPayload {
  // JEO id
  j: string;
  // Viewer's name: the PDF's "generated by" signature, as on the
  // logged-in route.
  n?: string;
  // Expiry, ms since epoch.
  e: number;
}

function signingKey(): Buffer {
  return createHmac('sha256', process.env.JWT_SECRET || 'supersecretjwtkey_change_me')
    .update('jeo-pdf-link')
    .digest();
}

function sign(payload: string): string {
  return createHmac('sha256', signingKey()).update(payload).digest('base64url');
}

export function createJeoPdfLinkToken(jeoId: string, viewerName: string | undefined, now = Date.now()): string {
  const payload: JeoPdfLinkPayload = { j: jeoId, e: now + JEO_PDF_LINK_TTL_MS, ...(viewerName ? { n: viewerName } : {}) };
  const encoded = Buffer.from(JSON.stringify(payload)).toString('base64url');
  return `${encoded}.${sign(encoded)}`;
}

// The JEO id and viewer name, or null if the token is malformed, tampered
// with, expired, or for a different JEO.
export function verifyJeoPdfLinkToken(
  token: string,
  jeoId: string,
  now = Date.now(),
): { viewerName?: string } | null {
  const [encoded, signature, extra] = token.split('.');
  if (!encoded || !signature || extra !== undefined) return null;
  const expected = Buffer.from(sign(encoded));
  const given = Buffer.from(signature);
  if (expected.length !== given.length || !timingSafeEqual(expected, given)) return null;
  let payload: JeoPdfLinkPayload;
  try {
    payload = JSON.parse(Buffer.from(encoded, 'base64url').toString('utf8'));
  } catch {
    return null;
  }
  if (payload.j !== jeoId || typeof payload.e !== 'number' || payload.e < now) return null;
  return { viewerName: typeof payload.n === 'string' ? payload.n : undefined };
}
