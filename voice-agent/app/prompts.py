# Sent as TTS immediately on call answer — not generated by the LLM, so the
# very first thing a customer hears is guaranteed to match the spec
# exactly, with no risk of the model paraphrasing it. This is the exact
# wording that was reserved ahead of time in Phase 2B as `REAL_LEAD_GREETING`
# for this real-lead-call flow.
